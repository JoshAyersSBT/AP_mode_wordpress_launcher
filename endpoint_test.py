@dataclass
class SSHConfig:
    host: str
    user: str
    port: int
    key_path: str
    password: str

def ssh_connect(cfg: SSHConfig) -> paramiko.SSHClient:
    cli = paramiko.SSHClient()
    cli.set_missing_host_key_policy(paramiko.AutoAddPolicy())
    kwargs = dict(hostname=cfg.host, username=cfg.user, port=cfg.port, timeout=12)
    if cfg.key_path.strip():
        kwargs["key_filename"] = cfg.key_path.strip()
    if cfg.password.strip():
        kwargs["password"] = cfg.password.strip()
    cli.connect(**kwargs)
    return cli

def ssh_run(ssh: paramiko.SSHClient, cmd: str) -> Tuple[int, str, str]:
    stdin, stdout, stderr = ssh.exec_command(cmd)
    out = stdout.read().decode("utf-8", errors="replace")
    err = stderr.read().decode("utf-8", errors="replace")
    code = stdout.channel.recv_exit_status()
    return code, out, err

def sftp_read_text(sftp: paramiko.SFTPClient, path: str, max_bytes: int = 512_000) -> str:
    with sftp.open(path, "rb") as f:
        data = f.read(max_bytes)
    return data.decode("utf-8", errors="replace")

def sftp_mkdir_p(sftp: paramiko.SFTPClient, remote_dir: str) -> None:
    remote_dir = remote_dir.replace("\\", "/").rstrip("/")
    if not remote_dir:
        return
    parts = remote_dir.split("/")
    path = ""
    for part in parts:
        if part == "":
            path = "/"
            continue
        path = ("/" + part) if path == "/" else (path + "/" + part)
        try:
            sftp.stat(path)
        except FileNotFoundError:
            sftp.mkdir(path)

def can_write_dir_sftp(sftp: paramiko.SFTPClient, remote_dir: str) -> bool:
    remote_dir = remote_dir.replace("\\", "/").rstrip("/") or "/"
    test_path = remote_dir.rstrip("/") + "/.write_test_tmp"
    try:
        with sftp.open(test_path, "w") as f:
            f.write("x")
        sftp.remove(test_path)
        return True
    except Exception:
        return False

def pick_writable_remote_path(
    ssh: paramiko.SSHClient,
    desired_path: str,
    *,
    fallback_dir: str = "/tmp",
    filename: str = "test_endpoints_generated.py",
) -> str:
    desired_path = desired_path.replace("\\", "/")
    desired_dir = posixpath.dirname(desired_path) or "/"

    sftp = ssh.open_sftp()
    try:
        try:
            sftp_mkdir_p(sftp, desired_dir)
            if can_write_dir_sftp(sftp, desired_dir):
                return desired_path
        except Exception:
            pass

        sftp_mkdir_p(sftp, fallback_dir)
        return posixpath.join(fallback_dir, f"{int(time.time())}_{filename}")
    finally:
        sftp.close()

def discover_files(ssh: paramiko.SSHClient, root_dir: str) -> List[str]:
    code, out, err = ssh_run(ssh, f"find {shlex.quote(root_dir)} -type f -print")
    if code != 0:
        raise RuntimeError(f"find failed: {err.strip()}")
    return [ln.strip() for ln in out.splitlines() if ln.strip()]

def build_endpoint_set(ssh: paramiko.SSHClient, root_dir: str) -> Tuple[List[str], List[str]]:
    files = discover_files(ssh, root_dir)
    assets = [f for f in files if is_asset(f)]

    def rel_from_root(abs_path: str) -> str:
        rd = root_dir.rstrip("/")
        if abs_path.startswith(rd + "/"):
            return abs_path[len(rd) + 1 :]
        return abs_path

    rels = [rel_from_root(f) for f in assets]
    static_eps = sorted({urlify_static(rp) for rp in rels})

    linked: Set[str] = set()
    sftp = ssh.open_sftp()
    try:
        for abs_path in assets:
            if not is_text(abs_path):
                continue
            try:
                txt = sftp_read_text(sftp, abs_path)
            except Exception:
                continue
            for u in extract_candidate_paths(txt):
                if u.startswith("/"):
                    linked.add(norm_web_path(u))
                else:
                    linked.add(norm_web_path(u.lstrip("./")))
    finally:
        sftp.close()

    linked_eps = sorted(linked - set(static_eps))
    return static_eps, linked_eps

def choose_monitor_ports(ssh: paramiko.SSHClient) -> List[int]:
    candidates: List[int] = []
    for svc in ("monitor.service", "lms-monitor.service", "lms_monitor.service", "lms.service"):
        _, txt, _ = ssh_run(ssh, f"systemctl cat {shlex.quote(svc)} 2>/dev/null || true")
        if txt.strip():
            p = guess_monitor_port_from_unit_text(txt)
            if p and p not in candidates:
                candidates.append(p)

    for p in (5000, 5050, 8000, 8080, 8888):
        if p not in candidates:
            candidates.append(p)

    _, out, _ = ssh_run(ssh, "ss -ltnp 2>/dev/null || netstat -ltnp 2>/dev/null || true")
    ports: Set[int] = set()
    for line in out.splitlines():
        for m in LISTEN_RE.finditer(line):
            try:
                ports.add(int(m.group(1)))
            except Exception:
                pass

    for p in sorted(ports):
        if p >= 1024 and p not in candidates:
            candidates.append(p)

    return candidates[:12]

