class Worker(QThread):
    log = pyqtSignal(str)
    progress = pyqtSignal(int)
    step = pyqtSignal(str)
    tests_ready = pyqtSignal(list)
    finished_ok = pyqtSignal()
    finished_err = pyqtSignal(str)

    def __init__(
        self,
        cfg: SSHConfig,
        *,
        captive_root: str,
        repo_root: str,
        base_url_default: str,
        monitor_host_default: str,
        remote_test_path: str,
        run_pytest: bool,
    ) -> None:
        super().__init__()
        self.cfg = cfg
        self.captive_root = captive_root
        self.repo_root = repo_root
        self.base_url_default = base_url_default
        self.monitor_host_default = monitor_host_default
        self.remote_test_path = remote_test_path
        self.run_pytest = run_pytest

    def _emit(self, s: str) -> None:
        self.log.emit(s)

    def run(self) -> None:
        ssh = None
        try:
            self.progress.emit(0)
            self.step.emit("Connecting over SSH…")
            self._emit(f"[SSH] Connecting to {self.cfg.user}@{self.cfg.host}:{self.cfg.port}")
            ssh = ssh_connect(self.cfg)
            self._emit("[SSH] Connected.")
            self.progress.emit(10)

            self.step.emit("Checking captive portal directory…")
            _, out, _ = ssh_run(ssh, f"test -d {shlex.quote(self.captive_root)} && echo OK || echo MISSING")
            if "OK" not in out:
                raise RuntimeError(f"Remote captive portal dir missing: {self.captive_root}")
            self.progress.emit(18)

            self.step.emit("Checking repo root…")
            _, out, _ = ssh_run(ssh, f"test -d {shlex.quote(self.repo_root)} && echo OK || echo MISSING")
            if "OK" not in out:
                raise RuntimeError(f"Remote repo root missing: {self.repo_root}")
            self.progress.emit(22)

            self.step.emit("Discovering endpoints…")
            static_eps, linked_eps = build_endpoint_set(ssh, self.captive_root)
            self._emit(f"[DISCOVERY] Static endpoints: {len(static_eps)}")
            self._emit(f"[DISCOVERY] Linked routes: {len(linked_eps)}")
            self.progress.emit(35)

            self.step.emit("Discovering monitor ports…")
            monitor_ports = choose_monitor_ports(ssh)
            self._emit(f"[MONITOR] Candidate ports: {monitor_ports}")
            self.progress.emit(45)

            # --- NEW: generate tests from an on-disk template file (no .format brace issues) ---
            self.step.emit("Generating pytest file from template…")
            try:
                from pathlib import Path
                template_path = Path(__file__).resolve().parent / "templates" / "pytest_endpoints_template.py"
                if not template_path.exists():
                    raise RuntimeError(f"Missing template file: {template_path}")
                test_text = render_test_file_from_template(
                    template_path,
                    static_eps=static_eps,
                    linked_eps=linked_eps,
                    monitor_ports=monitor_ports,
                    base_url_default=self.base_url_default,
                    monitor_host_default=self.monitor_host_default,
                )
            except Exception as e:
                raise RuntimeError(f"Template-based generation failed: {e}")
            self.progress.emit(55)

            self.step.emit("Uploading tests to Pi…")
            desired_remote_test_path = self.remote_test_path.replace("\\", "/").strip() or "/tmp/test_endpoints_generated.py"

            remote_test_path = pick_writable_remote_path(
                ssh,
                desired_remote_test_path,
                fallback_dir="/tmp",
                filename="test_endpoints_generated.py",
            )
            remote_dir = posixpath.dirname(remote_test_path)

            self._emit(f"[DEBUG] desired_remote_test_path={desired_remote_test_path}")
            self._emit(f"[DEBUG] selected_remote_test_path={remote_test_path}")
            self._emit(f"[DEBUG] selected_remote_dir={remote_dir}")

            sftp = ssh.open_sftp()
            try:
                sftp_mkdir_p(sftp, remote_dir)
                with sftp.open(remote_test_path, "w") as f:
                    f.write(test_text)
            finally:
                sftp.close()

            self._emit(f"[UPLOAD] Wrote: {remote_test_path}")
            self.progress.emit(70)

            if not self.run_pytest:
                planned = [
                    dict(name="static_endpoints", classname="generated", time="0", status="pending",
                        message=f"{len(static_eps)} endpoints"),
                    dict(name="linked_routes", classname="generated", time="0", status="pending",
                        message=f"{len(linked_eps)} routes"),
                    dict(name="monitor_ports", classname="generated", time="0", status="pending",
                        message=f"{len(monitor_ports)} ports"),
                ]
                self.tests_ready.emit(planned)
                self.progress.emit(100)
                self.step.emit("Done (generated only).")
                self.finished_ok.emit()
                return

            self.step.emit("Running pytest remotely…")

            junit_remote = f"/tmp/endpoint_tests_{int(time.time())}.xml"
            log_remote = f"/tmp/endpoint_tests_{int(time.time())}.log"

            # Ensure pytest exists (auto-install if missing), run, capture rc, and log output deterministically.
            cmd = (
                f"cd {shlex.quote(self.repo_root)} && "
                f"python3 -m pip -q show pytest >/dev/null 2>&1 || python3 -m pip install --user -U pytest >/dev/null 2>&1; "
                f"python3 -m pytest -q --junitxml={shlex.quote(junit_remote)} "
                f"{shlex.quote(remote_test_path)} "
                f"> {shlex.quote(log_remote)} 2>&1; "
                f"echo __PYTEST_RC=$?"
            )
            self._emit(f"[RUN] {cmd}")

            _, out, err = ssh_run(ssh, cmd)
            if err.strip():
                self._emit("[stderr]\n" + err.rstrip())
            if out.strip():
                self._emit(out.rstrip())

            m = re.search(r"__PYTEST_RC=(\d+)", out)
            rc = int(m.group(1)) if m else 999
            self._emit(f"[RESULT] pytest exit code: {rc}")
            self.progress.emit(85)

            self.step.emit("Checking for JUnit XML…")
            _, ls_out, _ = ssh_run(ssh, f"ls -l {shlex.quote(junit_remote)} 2>/dev/null || echo MISSING")
            self._emit(f"[DEBUG] junit check: {ls_out.strip()}")

            if "MISSING" in ls_out:
                _, tail_out, _ = ssh_run(ssh, f"tail -n 120 {shlex.quote(log_remote)} 2>/dev/null || true")
                if tail_out.strip():
                    self._emit("[DEBUG] pytest log tail:\n" + tail_out.rstrip())
                raise RuntimeError(f"JUnit XML not found at {junit_remote}")

            self.step.emit("Fetching JUnit XML…")
            sftp = ssh.open_sftp()
            try:
                with sftp.open(junit_remote, "r") as f:
                    xml_text = f.read()
            finally:
                sftp.close()

            tests = parse_junit(xml_text)
            self.tests_ready.emit(tests)
            self.progress.emit(100)
            self.step.emit("Complete.")
            self.finished_ok.emit()

        except Exception:
            self.finished_err.emit(traceback.format_exc())
        finally:
            try:
                if ssh:
                    ssh.close()
            except Exception:
                pass

