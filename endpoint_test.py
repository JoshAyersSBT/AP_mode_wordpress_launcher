def is_asset(path: str) -> bool:
    return os.path.splitext(path.lower())[1] in ASSET_EXTS

def is_text(path: str) -> bool:
    return os.path.splitext(path.lower())[1] in TEXT_EXTS

def norm_web_path(p: str) -> str:
    p = p.replace("\\", "/")
    if not p.startswith("/"):
        p = "/" + p
    p = re.sub(r"/{2,}", "/", p)
    p = p.replace("/./", "/")
    return p

def extract_candidate_paths(text: str) -> Set[str]:
    out: Set[str] = set()
    for rx in (HREF_RE, FORM_ACTION_RE, FETCH_RE, XHR_RE):
        for m in rx.finditer(text):
            out.add(m.group(1).strip())

    cleaned: Set[str] = set()
    for u in out:
        if not u or u.startswith("#"):
            continue
        if u.startswith(("http://", "https://", "//", "mailto:", "tel:", "data:")):
            continue
        u = u.split("#", 1)[0]
        cleaned.add(u)
    return cleaned

def urlify_static(rel_path: str) -> str:
    rp = rel_path.replace("\\", "/")
    if rp.lower() == "index.html":
        return "/"
    return norm_web_path(rp)

def guess_monitor_port_from_unit_text(unit_text: str) -> Optional[int]:
    m = FLASK_RUN_RE.search(unit_text)
    if m:
        return int(m.group(1))
    m = PORT_RE.search(unit_text)
    if m:
        return int(m.group(1))
    return None

def parse_junit(xml_text: str) -> List[dict]:
    root = ET.fromstring(xml_text)
    out: List[dict] = []
    suites = [root] if root.tag == "testsuite" else list(root.findall(".//testsuite"))

    for suite in suites:
        for tc in suite.findall(".//testcase"):
            name = tc.attrib.get("name", "")
            classname = tc.attrib.get("classname", "")
            t = tc.attrib.get("time", "0")
            status = "pass"
            msg = ""

            if tc.find("skipped") is not None:
                status = "skip"
                node = tc.find("skipped")
                msg = (node.attrib.get("message", "") if node is not None else "") or (node.text or "")
            elif tc.find("failure") is not None:
                status = "fail"
                node = tc.find("failure")
                msg = (node.attrib.get("message", "") if node is not None else "") or (node.text or "")
            elif tc.find("error") is not None:
                status = "error"
                node = tc.find("error")
                msg = (node.attrib.get("message", "") if node is not None else "") or (node.text or "")

            out.append(dict(
                name=name,
                classname=classname,
                time=t,
                status=status,
                message=(msg or "").strip(),
            ))
    return out

